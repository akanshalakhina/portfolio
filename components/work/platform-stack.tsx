"use client";

import { motion, useMotionValue, useSpring, useTransform } from "framer-motion";
import Image from "next/image";
import { useRef } from "react";

const SCREENS = [
  { src: "/work/ai-layer-summary.jpg", alt: "AI Management Summary generated by the AI layer", w: 1360, h: 1000 },
  { src: "/work/whizunik-dashboard.jpg", alt: "WhizUnik Command executive dashboard", w: 1600, h: 861 },
  { src: "/work/adventra-marketplace.jpg", alt: "Marketplace Integration Hub with the 8-step Amazon order workflow", w: 1600, h: 900 },
];

const CHIPS = [
  { text: "Amazon SP-API · live", x: "4%", y: "9%", d: 0 },
  { text: "GST e-Way Bill", x: "66%", y: "4%", d: 0.6 },
  { text: "UTR bank reconciliation", x: "50%", y: "88%", d: 1.2 },
  { text: "Maker–checker approvals", x: "4%", y: "80%", d: 1.8 },
];

export function PlatformStack() {
  const ref = useRef<HTMLDivElement>(null);
  const mx = useMotionValue(0);
  const my = useMotionValue(0);
  const rx = useSpring(useTransform(my, [-0.5, 0.5], [18, 6]), { stiffness: 120, damping: 18 });
  const ry = useSpring(useTransform(mx, [-0.5, 0.5], [-26, -10]), { stiffness: 120, damping: 18 });

  return (
    <div
      ref={ref}
      className="relative h-full w-full overflow-hidden"
      style={{ perspective: 1400 }}
      onPointerMove={(e) => {
        const r = ref.current!.getBoundingClientRect();
        mx.set((e.clientX - r.left) / r.width - 0.5);
        my.set((e.clientY - r.top) / r.height - 0.5);
      }}
      onPointerLeave={() => {
        mx.set(0);
        my.set(0);
      }}
    >
      <div className="absolute inset-0 bg-[radial-gradient(60%_50%_at_50%_50%,rgba(61,216,255,0.16),transparent_70%)]" />

      <motion.div
        className="absolute left-1/2 top-1/2 w-[84%]"
        style={{
          rotateX: rx,
          rotateY: ry,
          rotateZ: 4,
          x: "-50%",
          y: "-50%",
          transformStyle: "preserve-3d",
        }}
      >
        {SCREENS.map((s, i) => (
          <motion.div
            key={s.src}
            className="overflow-hidden rounded-xl border border-white/15 bg-white shadow-[0_40px_80px_-30px_rgba(0,0,0,0.9)]"
            style={{
              position: i === 0 ? "relative" : "absolute",
              inset: i === 0 ? undefined : 0,
              transformStyle: "preserve-3d",
            }}
            initial={{ z: 0, x: 0, y: 0, opacity: 0 }}
            whileInView={{ z: i * 90, x: `${i * 9}%`, y: `${-i * 12}%`, opacity: 1 }}
            viewport={{ once: true, margin: "-15% 0px" }}
            transition={{ duration: 1.2, delay: 0.15 * i, ease: [0.22, 1, 0.36, 1] }}
          >
            <Image src={s.src} alt={s.alt} width={s.w} height={s.h} className="h-auto w-full object-cover object-top" sizes="(min-width:1024px) 40vw, 80vw" />
            <div className="pointer-events-none absolute inset-0 bg-gradient-to-br from-white/10 via-transparent to-ink/30" />
          </motion.div>
        ))}
      </motion.div>

      {CHIPS.map((c) => (
        <motion.span
          key={c.text}
          className="absolute z-10 whitespace-nowrap rounded-full border border-aqua/30 bg-ink/80 px-3 py-1.5 font-mono text-[10px] text-aqua shadow-lg backdrop-blur sm:text-[11px]"
          style={{ left: c.x, top: c.y }}
          animate={{ y: [0, -8, 0] }}
          transition={{ duration: 4, repeat: Infinity, delay: c.d, ease: "easeInOut" }}
        >
          ● {c.text}
        </motion.span>
      ))}
    </div>
  );
}
